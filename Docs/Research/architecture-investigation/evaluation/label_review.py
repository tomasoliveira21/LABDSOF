"""Label-review table for #149 AC-2 (#234, spec Docs/specs/234-ai-triage-end-to-end.md D6).

Writes label-review/labels.md from the case files: urgent references first, then expected abstentions, then the rest,
each group by split (holdout, test, dev) and ID; one line per case with its text and current labels, and no model
output. The reviewer's guide is label-review/README.md.

    python -I label_review.py          # write the table
    python -I label_review.py --check  # self-checks, and the committed table is what this script writes

Standard library only.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
CASE_FILES = ["holdout.jsonl", "cases.jsonl", "dev-extra.jsonl"]
TABLE = HERE / "label-review" / "labels.md"
SPLITS = ["holdout", "test", "dev"]
GROUPS = [("urgent", "Urgent references (minimum High or Critical)"), ("abstain", "Expected abstentions"),
          ("other", "Other cases (minimum Low or Medium)")]
failures: list[str] = []


def check(condition: bool, name: str) -> None:
    print(("ok " if condition else "FAILED ") + name)
    if not condition:
        failures.append(name)


def load(files: list[Path]) -> list[dict]:
    return [json.loads(line) for path in files for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def group(case: dict) -> str:
    expected = case["expected"]
    if expected["abstain"]:
        return "abstain"
    return "urgent" if expected["minimum_priority"] in ("High", "Critical") else "other"


def cell(value: object) -> str:
    """One table cell on one line: a pipe is escaped, a line break is shown as ↵."""
    text = "" if value is None else str(value)
    return text.replace("\\", "\\\\").replace("|", "\\|").replace("\r\n", " ↵ ").replace("\n", " ↵ ").replace("\r", " ↵ ")


def render(cases: list[dict]) -> str:
    ordered = sorted(cases, key=lambda c: ([g for g, _ in GROUPS].index(group(c)), SPLITS.index(c["split"]), c["id"]))
    lines = ["# Label review table", "",
             "Generated by [`label_review.py`](../label_review.py) from "
             + ", ".join(f"[`{name}`](../{name})" for name in CASE_FILES)
             + "; do not edit by hand. How to review: [README](README.md). Comment on the line of each label you"
             " would change.", ""]
    for key, title in GROUPS:
        members = [c for c in ordered if group(c) == key]
        lines += [f"## {title}: {len(members)} cases", "",
                  "| ID | Split | Text | Category | Minimum priority | Abstain | Tags |", "|---|---|---|---|---|---|---|"]
        lines += ["| " + " | ".join(cell(v) for v in (c["id"], c["split"], c["input"]["text"], c["expected"]["category"],
                                                       c["expected"]["minimum_priority"],
                                                       "yes" if c["expected"]["abstain"] else "no",
                                                       ", ".join(c.get("tags", [])))) + " |" for c in members]
        lines.append("")
    return "\n".join(lines)


def self_check(cases: list[dict]) -> None:
    table = render(cases)
    rows = [line for line in table.splitlines() if line.startswith("| ") and not line.startswith("| ID ")]
    ids = [row.split(" | ")[0][2:] for row in rows]
    check(sorted(ids) == sorted(c["id"] for c in cases) and len(set(ids)) == len(ids),
          "234 AC-3 every case has one line")
    groups = [group(next(c for c in cases if c["id"] == i)) for i in ids]
    check(groups == sorted(groups, key=[g for g, _ in GROUPS].index) and groups[0] == "urgent",
          "234 AC-3 urgent and abstention cases come first")
    tricky = {"id": "Z001", "split": "dev", "input": {"text": "a | b\nc\r\nd \\| e"}, "tags": [],
              "expected": {"category": "Other", "minimum_priority": "Low", "abstain": False}}
    tricky_rows = [line for line in render([tricky]).splitlines() if line.startswith("| Z001")]
    check(len(tricky_rows) == 1 and tricky_rows[0].count(" | ") == 6 and "a \\| b ↵ c ↵ d \\\\\\| e" in tricky_rows[0],
          "234 AC-3 a pipe or newline in a text cannot break a line")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    cases = load([HERE / name for name in CASE_FILES])
    if args.check:
        self_check(cases)
        committed = TABLE.read_text(encoding="utf-8").replace("\r\n", "\n") if TABLE.exists() else None
        check(committed == render(cases), "234 AC-3 the table is what the script writes")
        return 1 if failures else 0
    TABLE.parent.mkdir(exist_ok=True)
    TABLE.write_text(render(cases), encoding="utf-8", newline="\n")
    print(f"{TABLE.name}: {len(cases)} cases")
    return 0


if __name__ == "__main__":
    sys.exit(main())
